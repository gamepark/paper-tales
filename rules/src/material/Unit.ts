/** Every copy of the given units */
export const deckOf = (cards: Unit[]): Unit[] => cards.flatMap((card) => Array<Unit>(unitCopies[card]).fill(card))

/** The 81 unit cards of the base game */
export const baseGameDeck = deckOf(baseGameUnits)

export function howManyCardCopies(unit: Unit): number {
  return unitCopies[unit]
}
